using System.Text;
using ApexPost.Application.DTOs;
using ApexPost.Application.Reports;
using ApexPost.Domain.Branches;
using ApexPost.Domain.Transactions;
using ApexPost.Infrastructure.Persistence;
using ApexPost.Infrastructure.Repositories.Queries;
using Microsoft.EntityFrameworkCore;

namespace ApexPost.UnitTests.Measurements;

/// <summary>
/// Writes the SQL that EF Core generates for the important queries to docs/perf/ef-tostring.sql with ToQueryString().
/// Nothing runs on a server: the filters are the default ones of a screen, 14 days up to the given day.
/// </summary>
public sealed class GeneratedSqlMeasurements
{
    private static readonly DateOnly To = new(2026, 11, 1);
    private static readonly DateOnly From = To.AddDays(-ReportService.DefaultRangeDays);
    private static readonly BranchCode Branch = new("BR001");

    [Fact]
    [Trait("Category", "Measurement")]
    public void Writes_the_generated_sql_of_the_important_queries()
    {
        using var database = new ApexPostDbContext(new DbContextOptionsBuilder<ApexPostDbContext>()
            .UseSqlServer("Server=unused;Database=unused")
            .Options);
        var filter = new ReportFilter(Branch, From, To);
        var list = SqlTransactionQueries.Matching(database, new TransactionFilter(Branch));
        var relevant = SqlReportQueries.Relevant(database, filter);

        var text = new StringBuilder()
            .AppendLine("-- Generated by GeneratedSqlMeasurements with ToQueryString(), EF Core 10.")
            .Append(Section("1. GET /Transactions: one page of a branch", SqlTransactionQueries.PageOf(
                list,
                new PageRequest())))
            .Append(Section("2. GET /Reports/ShippingVolume: groups of one branch", SqlReportQueries.ShippingGroups(
                database,
                filter)))
            .Append(Section("3. GET /Reports/MoneyOrders: rows of the period", relevant))
            .Append(Section("4. GET /Reports/MoneyOrders: total of the period", relevant.Select(row => row.Id)))
            .ToString();

        File.WriteAllText(Path.Combine(RepositoryRoot(), "docs", "perf", "ef-tostring.sql"), text);
    }

    private static string Section<T>(string title, IQueryable<T> query) =>
        $"{Environment.NewLine}-- {title}{Environment.NewLine}{query.ToQueryString()}{Environment.NewLine}";

    private static string RepositoryRoot()
    {
        var folder = new DirectoryInfo(AppContext.BaseDirectory);
        while (folder is not null && folder.GetFiles("*.slnx").Length == 0)
        {
            folder = folder.Parent;
        }

        return folder?.FullName ?? throw new InvalidOperationException("The solution folder was not found.");
    }
}
